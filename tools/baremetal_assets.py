"""Turns PNG files into a C header of images for ports/rpi, which has no
filesystem: load-image finds them there by name.

  tools/baremetal_assets.py -o out/rpi/gen/baremetal_assets.h examples/sdl2_tiles.png ...

Each image becomes 0xAARRGGBB words. The PNG decoder is here (zlib only,
no PIL needed): 8-bit gray, gray+alpha, RGB, RGBA, and palettes of 1, 2,
4 or 8 bits (with tRNS), not interlaced.
"""

import argparse
import os
import struct
import zlib


def paeth(a, b, c):
  p = a + b - c
  pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
  if pa <= pb and pa <= pc:
    return a
  return b if pb <= pc else c


def decode_png(data):
  if data[:8] != b'\x89PNG\r\n\x1a\n':
    raise ValueError('not a PNG')
  pos, idat, palette, trns = 8, b'', None, None
  while pos < len(data):
    n, kind = struct.unpack('>I4s', data[pos:pos + 8])
    body = data[pos + 8:pos + 8 + n]
    pos += 12 + n
    if kind == b'IHDR':
      w, h, depth, ctype, _, _, interlace = struct.unpack('>IIBBBBB', body)
    elif kind == b'PLTE':
      palette = [tuple(body[i:i + 3]) for i in range(0, len(body), 3)]
    elif kind == b'tRNS':
      trns = body
    elif kind == b'IDAT':
      idat += body
    elif kind == b'IEND':
      break
  if interlace:
    raise ValueError('interlaced PNG')
  channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
  if ctype != 3 and depth != 8:
    raise ValueError('only 8-bit channels (or palettes)')
  bits = depth * channels
  stride = (w * bits + 7) // 8
  bpp = max(1, bits // 8)
  raw = zlib.decompress(idat)
  rows, prev = [], bytearray(stride)
  for y in range(h):
    f = raw[y * (stride + 1)]
    line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
    for i in range(stride):
      a = line[i - bpp] if i >= bpp else 0
      b = prev[i]
      c = prev[i - bpp] if i >= bpp else 0
      if f == 1:
        line[i] = (line[i] + a) & 255
      elif f == 2:
        line[i] = (line[i] + b) & 255
      elif f == 3:
        line[i] = (line[i] + (a + b) // 2) & 255
      elif f == 4:
        line[i] = (line[i] + paeth(a, b, c)) & 255
    rows.append(line)
    prev = line
  pixels = []
  for line in rows:
    for x in range(w):
      if ctype == 3:
        per = 8 // depth
        v = (line[x // per] >> (8 - depth * (x % per + 1))) & ((1 << depth) - 1)
        r, g, b = palette[v]
        a = trns[v] if trns and v < len(trns) else 255
      else:
        p = line[x * channels:(x + 1) * channels]
        if ctype == 0:
          r = g = b = p[0]; a = 255
        elif ctype == 4:
          r = g = b = p[0]; a = p[1]
        elif ctype == 2:
          r, g, b = p; a = 255
        else:
          r, g, b, a = p
      pixels.append((a << 24) | (r << 16) | (g << 8) | b)
  return w, h, pixels


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument('-o', required=True)
  ap.add_argument('files', nargs='*')
  args = ap.parse_args()
  out = ['// Generated by tools/baremetal_assets.py from: ' + ' '.join(args.files), '']
  table = []
  for i, name in enumerate(args.files):
    w, h, px = decode_png(open(name, 'rb').read())
    out.append('static const uint32_t asset_%d[%d] = {' % (i, len(px)))
    for k in range(0, len(px), 8):
      out.append('  ' + ', '.join('0x%08x' % v for v in px[k:k + 8]) + ',')
    out.append('};')
    table.append('  {"%s", %d, %d, asset_%d},' % (os.path.basename(name), w, h, i))
  out.append('')
  out.append('static const struct { const char *name; int w, h; const uint32_t *px; } baremetal_assets[] = {')
  out += table
  out.append('  {0, 0, 0, 0},')
  out.append('};')
  with open(args.o, 'w') as f:
    f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
  main()
