#!/usr/bin/env python3
"""Writes the table of C functions that a static lugforth offers to the Forth words that look
them up by name (dlsym finds nothing in a static executable). Names come from the .fs sources:
`z" open" 3 sysfunc open` and `z" SDL_Init" 1 sdl SDL_Init`.  Usage: static_syms.py OUT.h [--sdl]"""
import glob, re, sys, os
ROOT = os.environ.get('LUG_ROOT') or os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
out = sys.argv[1]
with_sdl = '--sdl' in sys.argv
names = set()
pat = re.compile(r'z" ([A-Za-z_][A-Za-z_0-9]*)" +\d+ +(sysfunc|sdl|sdlimg|sdlttf|sdlmix|sofunc)\b')
dl = re.compile(r'z" ([A-Za-z_][A-Za-z_0-9]*)" +[^\n]*?\bdlsym\b')
for f in sorted(glob.glob(ROOT + 'common/*.fs') + glob.glob(ROOT + 'ports/posix/*.fs')):
    if f.endswith('_tests.fs'):
        continue
    for line in open(f, encoding='utf-8', errors='ignore'):
        for m in pat.finditer(line):
            names.add(m.group(1))
        for m in dl.finditer(line):
            names.add(m.group(1))
names.discard('dlsym')
libc = sorted(n for n in names if not n.startswith(('SDL_', 'IMG_', 'TTF_', 'Mix_')))
sdl = sorted(n for n in names if n.startswith(('SDL_', 'IMG_', 'TTF_', 'Mix_')))
with open(out, 'w') as o:
    o.write('// Generated by tools/static_syms.py: do not edit.\n')
    for n in libc + (sdl if with_sdl else []):
        o.write('extern char lugsym_%s[] __asm__("%s");\n' % (n, n))
    o.write('#define LUG_SYMS \\\n')
    for n in libc + (sdl if with_sdl else []):
        o.write('  {"%s", (void *) lugsym_%s}, \\\n' % (n, n))
    o.write('  {0, 0}\n')
print('%d libc names, %d SDL names%s' % (len(libc), len(sdl), '' if with_sdl else ' (not linked)'))
