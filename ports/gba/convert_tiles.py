# Converts an 8x8-tile sheet (examples/games/sdl2_tiles.png, or any PNG that is a
# row of NxN tiles) into a C header of plain RGB15 pixels -- no palette, no
# indexing, matching mode 3 (direct 16-bit framebuffer, see platform.fs's
# gba-mode3/gba-dot) rather than the GBA's tile/sprite hardware. Good enough
# for a first port: this is the same tradeoff bench_lines.tal made (plain
# per-pixel blits over the real hardware feature), simple and correct,
# not the fastest a GBA could do this.
#
# A pixel with alpha < 128 becomes the sentinel 0xffff ("transparent, skip
# it"): rgb15's own r|g<<5|b<<10 with 5-bit channels never sets bit 15
# (max value 0x7fff), so that bit is free to mean "not a real color" -- see
# `draw-tile` in platform.fs.
#
# Does not touch the source PNG: point it at whatever tile sheet exists
# (examples/games/sdl2_tiles.png by default), including one hand-edited outside
# make_sdl2_tiles.fs/.py.
#
#   python3 ports/gba/convert_tiles.py examples/games/sdl2_tiles.png ports/gba/tiles_data.h

import sys
from PIL import Image

src = sys.argv[1] if len(sys.argv) > 1 else "examples/games/sdl2_tiles.png"
dst = sys.argv[2] if len(sys.argv) > 2 else "ports/gba/tiles_data.h"
tile_size = int(sys.argv[3]) if len(sys.argv) > 3 else 8

im = Image.open(src).convert("RGBA")
w, h = im.size
if w % tile_size or h != tile_size:
    print(f"expected a {tile_size}-high strip whose width is a multiple of "
          f"{tile_size}, got {w}x{h}")
    sys.exit(1)
n_tiles = w // tile_size

TRANSPARENT = 0xFFFF
pixels = []
for t in range(n_tiles):
    for y in range(tile_size):
        for x in range(tile_size):
            r, g, b, a = im.getpixel((t * tile_size + x, y))
            if a < 128:
                pixels.append(TRANSPARENT)
            else:
                pixels.append((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10))

with open(dst, "w") as f:
    f.write("// Generated by ports/gba/convert_tiles.py from " + src + "\n")
    f.write("// -- do not edit by hand, and do not regenerate the .png from\n")
    f.write("// here: it is edited directly, see ports/gba/README.md.\n\n")
    f.write(f"#define GBA_TILE_SIZE {tile_size}\n")
    f.write(f"#define GBA_TILE_COUNT {n_tiles}\n")
    f.write(f"#define GBA_TILE_TRANSPARENT 0x{TRANSPARENT:04x}\n\n")
    f.write("static const unsigned short gba_tiles_data[] = {\n")
    for i in range(0, len(pixels), 16):
        row = pixels[i:i + 16]
        f.write("  " + ", ".join(f"0x{p:04x}" for p in row) + ",\n")
    f.write("};\n")

print(f"{src}: {n_tiles} {tile_size}x{tile_size} tiles -> {dst} "
      f"({len(pixels) * 2} bytes)")
