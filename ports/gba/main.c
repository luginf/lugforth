int main(int argc, char *argv[]) {
#ifndef LUGFORTH_SIM
  REG_DEBUG_ENABLE = 0xc0de;
  void *heap = heap_mem;
#else
  void *heap = malloc(HEAP_SIZE);
#endif
  forth_init(argc, argv, heap, HEAP_SIZE, boot, sizeof(boot));
  for (;;) { g_sys->rp = forth_run(g_sys->rp); }
  return 0;
}
