// Plain RGB15 pixels, no palette, generated by convert_tiles.py from
// examples/games/sdl2_tiles.png; see platform.fs's draw-tile. Available under
// LUGFORTH_SIM too, so tile-drawing Forth code can be developed there.
#include "ports/gba/tiles_data.h"
static void *gba_tiles(void) { return (void *) gba_tiles_data; }

// The GBA has 256K of slower EWRAM plus 32K of fast IWRAM; this heap lives
// in EWRAM (see gba.ld) and is deliberately the same size already proven
// working on pico-ice's RP2040 (which also has no PSRAM and a comparable
// total). STACK_CELLS likewise matches pico-ice.
#ifndef LUGFORTH_SIM
# define HEAP_SIZE (150 * 1024)
#else
# define HEAP_SIZE (300 * 1024)
#endif
#define STACK_CELLS (4 * 1024)

// ---- minimal GBA hardware access: no libgba/devkitARM, just the fixed
// memory-mapped register addresses every GBA reference documents. Exposed
// to Forth as addresses returned by opcodes (gba_reg_*, gba_vram), not as
// hardcoded literals in platform.fs, so LUGFORTH_SIM can point them at
// ordinary heap memory instead of real (unmapped, segfaulting-on-POSIX)
// hardware addresses: this is what lets the exact same Forth graphics code
// be developed and unit-tested in the simulator. ----
#ifndef LUGFORTH_SIM

#define REG_DISPCNT  (*(volatile unsigned short *) 0x04000000)
#define REG_VCOUNT   (*(volatile unsigned short *) 0x04000006)
#define REG_KEYINPUT (*(volatile unsigned short *) 0x04000130)

static void *gba_reg_dispcnt(void)  { return (void *) 0x04000000; }
static void *gba_reg_vcount(void)   { return (void *) 0x04000006; }
static void *gba_reg_keyinput(void) { return (void *) 0x04000130; }
static void *gba_vram(void)         { return (void *) 0x06000000; }

// mGBA's emulator-only debug console (https://mgba.io, "Debugging" ->
// "Using the debugger console" documents the same addresses): write a
// NUL-terminated string to 0x4FFF600, then a level (0-4) with 0x100 set to
// 0x4FFF700 to flush it. Harmless no-op on real hardware and on other
// emulators, since that memory is simply unmapped there.
#define REG_DEBUG_ENABLE (*(volatile unsigned short *) 0x4FFF780)
#define REG_DEBUG_FLAGS  (*(volatile unsigned short *) 0x4FFF700)
#define REG_DEBUG_STRING ((volatile char *) 0x4FFF600)

static unsigned gba_frame_count = 0;

static void gba_vblank_wait(void) {
  while (REG_VCOUNT < 160) {}
  while (REG_VCOUNT >= 160) {}
  gba_frame_count++;   // see REQUIRED_SYSTEM_SUPPORT in builtins.h: time only
                        // advances when Forth yields (`pause`), no timer
                        // interrupt is set up in this first prototype.
}

static unsigned gba_ms_ticks(void) {
  return gba_frame_count * 1000u / 60u;
}

static void gba_halt_forever(void) {
  for (;;) { __asm__ volatile("swi 0x02" ::: "memory"); }  // BIOS Halt
}

static void gba_mgba_print(const unsigned char *s, unsigned n) {
  if (n > 255) n = 255;
  for (unsigned i = 0; i < n; i++) REG_DEBUG_STRING[i] = s[i];
  REG_DEBUG_STRING[n] = 0;
  REG_DEBUG_FLAGS = 0x102;  // level 2 ("warning"): visible by default in mGBA's log
}

// A bump allocator for ALLOCATE/FREE/RESIZE (see builtins.h): no libc
// malloc, so no newlib heap/_sbrk to wire up for a first bare-metal boot.
// FREE is a no-op and RESIZE always grows a new block: fine for a prototype
// that never calls any of the three yet, wrong for one that frees a lot.
#define BUMP_HEAP_SIZE (16 * 1024)
static unsigned char bump_heap[BUMP_HEAP_SIZE];
static unsigned char *bump_next = bump_heap;
static void *gba_malloc(unsigned n) {
  if (bump_next + n > bump_heap + BUMP_HEAP_SIZE) return 0;
  void *p = bump_next;
  bump_next += n;
  return p;
}
static void gba_free(void *p) { (void) p; }
static void *gba_realloc(void *p, unsigned n) { (void) p; return gba_malloc(n); }

#else  // LUGFORTH_SIM: ordinary heap memory standing in for real registers/VRAM

static unsigned short sim_dispcnt, sim_vcount, sim_keyinput = 0xffff;
static unsigned char sim_vram[240 * 160 * 2];
static void *gba_reg_dispcnt(void)  { return &sim_dispcnt; }
static void *gba_reg_vcount(void)   { return &sim_vcount; }
static void *gba_reg_keyinput(void) { return &sim_keyinput; }  // stays "nothing pressed"
static void *gba_vram(void)         { return sim_vram; }

#endif  // !LUGFORTH_SIM

// A native tile blit and rect fill, called from platform.fs's
// draw-tile-tinted/gba-fill-rect: a per-pixel Forth loop (the original
// draw-tile-tinted, still in platform.fs's history) works, but each pixel
// costs a handful of interpreted word dispatches, and a full-screen redraw
// is 30000+ pixels -- confirmed by the user on real mgba: about 20 seconds
// per redraw, unplayable. Compiled C does the same math directly, no
// interpreter dispatch per pixel; portable (just array writes through
// gba_vram()/gba_tiles(), real addresses or the sim's stand-in arrays
// either way), so one implementation serves both builds. RGB15 channel
// layout (r bits0-4, g bits5-9, b bits10-14) has to match rgb15/tint in
// platform.fs exactly, see the comment there.
static void gba_blit_tile(int tile, int sx, int sy, unsigned tint) {
  unsigned short *vram = (unsigned short *) gba_vram();
  const unsigned short *src = (const unsigned short *) gba_tiles() + tile * 64;
  int tr = (tint >> 10) & 0x1f, tg = (tint >> 5) & 0x1f, tb = tint & 0x1f;
  int identity = (tr == 0x1f && tg == 0x1f && tb == 0x1f);
  int px, py;
  for (py = 0; py < 8; py++) {
    int y = sy + py;
    if (y < 0 || y >= 160) { src += 8; continue; }
    unsigned short *row = vram + y * 240;
    for (px = 0; px < 8; px++) {
      unsigned short c = *src++;
      int x = sx + px;
      if (c == 0xffff || x < 0 || x >= 240) continue;  // transparent / off-screen
      if (!identity) {
        int r = c & 0x1f, g = (c >> 5) & 0x1f, b = (c >> 10) & 0x1f;
        r = r * tr / 0x1f; g = g * tg / 0x1f; b = b * tb / 0x1f;
        c = r | (g << 5) | (b << 10);
      }
      row[x] = c;
    }
  }
}

static void gba_fill_rect(int x, int y, int w, int h, unsigned color) {
  unsigned short *vram = (unsigned short *) gba_vram();
  int i, j;
  for (j = 0; j < h; j++) {
    int yy = y + j;
    if (yy < 0 || yy >= 160) continue;
    unsigned short *row = vram + yy * 240;
    for (i = 0; i < w; i++) {
      int xx = x + i;
      if (xx >= 0 && xx < 240) row[xx] = (unsigned short) color;
    }
  }
}

